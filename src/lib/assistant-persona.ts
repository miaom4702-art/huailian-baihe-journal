export function detectMood(text: string): AssistantMood {
  if (!text) return "neutral";

  let best: AssistantMood = "neutral";
  let bestScore = 0;

  for (const [mood, keywords] of MOOD_KEYWORDS) {
    let score = 0;
    for (const keyword of keywords) {
      if (text.includes(keyword)) score += 1;
    }
    if (score > bestScore) {
      best = mood;
      bestScore = score;
    }
  }

  return best;
}
